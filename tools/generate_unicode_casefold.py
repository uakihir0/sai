#!/usr/bin/env python3
"""Generate the checked-in Unicode 16.0.0 full case-folding table.

Usage:
    python3 tools/generate_unicode_casefold.py CaseFolding-16.0.0.txt OUTPUT.rs

The input must be the official Unicode file with the SHA-256 recorded below.
"""

from __future__ import annotations

import hashlib
import pathlib
import sys


EXPECTED_INPUT_SHA256 = (
    "6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb"
)


def main() -> int:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)

    source_path = pathlib.Path(sys.argv[1])
    output_path = pathlib.Path(sys.argv[2])
    source = source_path.read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    if digest != EXPECTED_INPUT_SHA256:
        raise SystemExit(
            f"unexpected Unicode data digest: {digest}; "
            f"expected {EXPECTED_INPUT_SHA256}"
        )

    text = source.decode("utf-8")
    if not text.startswith("# CaseFolding-16.0.0.txt\n"):
        raise SystemExit("input is not CaseFolding-16.0.0.txt")

    mappings: dict[int, tuple[int, tuple[int, ...]]] = {}
    priorities = {"C": 1, "F": 2}
    for line in text.splitlines():
        fields = line.split("#", 1)[0].strip()
        if not fields:
            continue
        codepoint, status, mapping = (
            field.strip() for field in fields.split(";")[:3]
        )
        if status not in priorities:
            continue
        key = int(codepoint, 16)
        value = tuple(int(part, 16) for part in mapping.split())
        previous = mappings.get(key)
        if previous is None or priorities[status] > previous[0]:
            mappings[key] = (priorities[status], value)

    rows = [
        f'    (0x{codepoint:04X}, "{_rust_string(mapping)}"),'
        for codepoint, (_, mapping) in sorted(mappings.items())
    ]
    generated = "\n".join(
        [
            "// Generated by tools/generate_unicode_casefold.py.",
            "// Source: https://www.unicode.org/Public/16.0.0/ucd/CaseFolding.txt",
            "// Source SHA-256: " + EXPECTED_INPUT_SHA256,
            "// Copyright © 2024 Unicode, Inc.; see unicode/UNICODE-LICENSE.txt.",
            "#[rustfmt::skip]",
            "pub(super) const FULL_CASE_FOLD: &[(u32, &str)] = &[",
            *rows,
            "];",
            "",
        ]
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8", newline="\n") as output:
        output.write(generated)
    return 0


def _rust_string(codepoints: tuple[int, ...]) -> str:
    return "".join(f"\\u{{{codepoint:x}}}" for codepoint in codepoints)


if __name__ == "__main__":
    raise SystemExit(main())
