#!/usr/bin/env python3
"""Generate the checked-in Unicode 16.0.0 full case-folding table.

Usage:
    python3 tools/generate_unicode_data.py \
        CaseFolding-16.0.0.txt DerivedCoreProperties-16.0.0.txt OUTPUT.rs

The inputs must be the official Unicode files with the SHA-256 values recorded
below.
"""

from __future__ import annotations

import hashlib
import pathlib
import sys


EXPECTED_INPUT_SHA256 = (
    "6f1f9c588eb4a5c718d9e8f93b782685e5c7fec872cf05e8e6878053599e09bb"
)
EXPECTED_PROPERTIES_SHA256 = (
    "39d35161f2954497f69e08bdb9e701493f476a3d30222de20028feda36c1dabd"
)


def main() -> int:
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)

    source_path = pathlib.Path(sys.argv[1])
    properties_path = pathlib.Path(sys.argv[2])
    output_path = pathlib.Path(sys.argv[3])
    source = source_path.read_bytes()
    digest = hashlib.sha256(source).hexdigest()
    if digest != EXPECTED_INPUT_SHA256:
        raise SystemExit(
            f"unexpected Unicode data digest: {digest}; "
            f"expected {EXPECTED_INPUT_SHA256}"
        )

    text = source.decode("utf-8")
    if not text.startswith("# CaseFolding-16.0.0.txt\n"):
        raise SystemExit("input is not CaseFolding-16.0.0.txt")

    properties_source = properties_path.read_bytes()
    properties_digest = hashlib.sha256(properties_source).hexdigest()
    if properties_digest != EXPECTED_PROPERTIES_SHA256:
        raise SystemExit(
            f"unexpected Unicode property data digest: {properties_digest}; "
            f"expected {EXPECTED_PROPERTIES_SHA256}"
        )
    properties_text = properties_source.decode("utf-8")
    if not properties_text.startswith("# DerivedCoreProperties-16.0.0.txt\n"):
        raise SystemExit("input is not DerivedCoreProperties-16.0.0.txt")

    mappings: dict[int, tuple[int, tuple[int, ...]]] = {}
    priorities = {"C": 1, "F": 2}
    for line in text.splitlines():
        fields = line.split("#", 1)[0].strip()
        if not fields:
            continue
        codepoint, status, mapping = (
            field.strip() for field in fields.split(";")[:3]
        )
        if status not in priorities:
            continue
        key = int(codepoint, 16)
        value = tuple(int(part, 16) for part in mapping.split())
        previous = mappings.get(key)
        if previous is None or priorities[status] > previous[0]:
            mappings[key] = (priorities[status], value)

    default_ignorable_ranges: list[tuple[int, int]] = []
    for line in properties_text.splitlines():
        fields = line.split("#", 1)[0].strip()
        if not fields:
            continue
        code_range, property_name = (field.strip() for field in fields.split(";")[:2])
        if property_name != "Default_Ignorable_Code_Point":
            continue
        bounds = code_range.split("..", 1)
        start = int(bounds[0], 16)
        end = int(bounds[-1], 16)
        default_ignorable_ranges.append((start, end))

    rows = [
        f'    (0x{codepoint:04X}, "{_rust_string(mapping)}"),'
        for codepoint, (_, mapping) in sorted(mappings.items())
    ]
    ranges = [
        f"    (0x{start:04X}, 0x{end:04X}),"
        for start, end in default_ignorable_ranges
    ]
    generated = "\n".join(
        [
            "// Generated by tools/generate_unicode_data.py.",
            "// Unicode 16.0.0 UCD inputs; SHA-256:",
            "// CaseFolding.txt: " + EXPECTED_INPUT_SHA256,
            "// DerivedCoreProperties.txt: " + EXPECTED_PROPERTIES_SHA256,
            "// Copyright © 2024 Unicode, Inc.; see unicode/UNICODE-LICENSE.txt.",
            "#[rustfmt::skip]",
            "pub(super) const FULL_CASE_FOLD: &[(u32, &str)] = &[",
            *rows,
            "];",
            "",
            "#[rustfmt::skip]",
            "pub(super) const DEFAULT_IGNORABLE_RANGES: &[(u32, u32)] = &[",
            *ranges,
            "];",
            "",
        ]
    )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8", newline="\n") as output:
        output.write(generated)
    return 0


def _rust_string(codepoints: tuple[int, ...]) -> str:
    return "".join(f"\\u{{{codepoint:x}}}" for codepoint in codepoints)


if __name__ == "__main__":
    raise SystemExit(main())
